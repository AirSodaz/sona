#!/usr/bin/env node
/**
 * Regenerates the `SonaContext` domain operations from the exported free
 * functions in `platforms/uniffi/src/lib.rs`.
 *
 * Every `#[uniffi::export]` whose first parameter is an application-data
 * directory is an operation an explicit context can serve, so the handle must
 * offer all of them. Generating them keeps the two surfaces from drifting and
 * keeps 119 near-identical delegations out of hand-maintenance.
 *
 * Run after adding or changing a directory-scoped export:
 *
 *     pnpm run generate:sona-context
 *
 * The output is not rustfmt-shaped; the npm script formats afterwards.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const bindingPath = path.join(repoRoot, 'platforms', 'uniffi', 'src', 'lib.rs');
const contextPath = path.join(repoRoot, 'platforms', 'uniffi', 'src', 'sona_context.rs');

export const OPERATIONS_MARKER =
  '\n// ---------------------------------------------------------------------\n';

/** Operations the handle deliberately does not offer, with the reason. */
export const LIFECYCLE_ONLY = new Map([
  ['release_application_context', 'frees a directory rather than operating on one'],
  ['register_sync_secret_store_for_app_data_dir', 'registers a store before a context exists'],
]);

function read(filePath) {
  return fs.readFileSync(filePath, 'utf8').replace(/\r\n/gu, '\n');
}

function withoutInlineTests(source) {
  const index = source.search(/\n#\[cfg\(test\)\]\s*\nmod tests\s*\{/u);
  return index < 0 ? source : source.slice(0, index);
}

function splitArguments(text) {
  const out = [];
  let depth = 0;
  let current = '';
  for (const character of text) {
    if ('<(['.includes(character)) {
      depth += 1;
    } else if ('>)]'.includes(character)) {
      depth -= 1;
    }
    if (character === ',' && depth === 0) {
      out.push(current.trim());
      current = '';
    } else {
      current += character;
    }
  }
  if (current.trim()) {
    out.push(current.trim());
  }
  return out;
}

/** Bridge functions that accept a `ContextSource` rather than a directory. */
function contextAwareBridgeFunctions() {
  const names = new Set();
  const bridgeDir = path.join(repoRoot, 'platforms', 'uniffi', 'src');
  for (const entry of fs.readdirSync(bridgeDir)) {
    if (!entry.endsWith('_bridge.rs')) {
      continue;
    }
    const source = read(path.join(bridgeDir, entry));
    const module = entry.slice(0, -3);
    for (const match of source.matchAll(
      /pub\(crate\) (?:async )?fn (\w+)\(\s*context: impl Into<ContextSource>/gu,
    )) {
      names.add(`${module}::${match[1]}`);
    }
  }
  return names;
}

export function renderSonaContextOperations() {
  const binding = withoutInlineTests(read(bindingPath));
  const contextAware = contextAwareBridgeFunctions();
  const pattern =
    /#\[uniffi::export(?:[^\]]*)\]\s*pub (?<isAsync>async )?fn (?<name>\w+)\(\s*app_data_dir: String,?(?<rest>[^)]*)\)\s*->\s*(?<ret>[^{]+?)\s*\{\s*(?<call>\w+_bridge::\w+)\((?<args>[^;]*?)\)(?<awaited>\s*\.await)?\s*\}/gsu;

  const methods = [];
  const skipped = [];
  for (const match of binding.matchAll(pattern)) {
    const { name, ret, call } = match.groups;
    const isAsync = Boolean(match.groups.isAsync);
    const params = splitArguments(match.groups.rest.trim().replace(/,$/u, '')).filter(Boolean);
    const args = splitArguments(match.groups.args);
    if (args[0] !== 'app_data_dir') {
      skipped.push(name);
      continue;
    }

    // Recovery and diagnostics work on the filesystem rather than the database,
    // so they still take a directory; everything else takes this context.
    args[0] = contextAware.has(call) ? 'self.source()' : 'self.app_data_dir()';
    const signature = params.map((parameter) => `, ${parameter}`).join('');
    const keyword = isAsync ? 'pub async fn' : 'pub fn';
    methods.push(
      `    ${keyword} ${name}(&self${signature}) -> ${ret} {\n` +
        `        ${call}(${args.join(', ')})${isAsync ? '.await' : ''}\n` +
        `    }\n`,
    );
  }

  const unexpected = skipped.filter((name) => !LIFECYCLE_ONLY.has(name));
  if (unexpected.length > 0) {
    throw new Error(
      `unclassified directory-scoped exports: ${unexpected.join(', ')}. ` +
        'Add a SonaContext method or record the reason in LIFECYCLE_ONLY.',
    );
  }

  return {
    methods: methods.length,
    block:
      `${OPERATIONS_MARKER}` +
      '// Domain operations. Generated by scripts/generate-sona-context.js from the\n' +
      '// exported free functions so the two surfaces cannot drift; each hands the\n' +
      '// bridge this context instead of a directory to look up.\n' +
      '#[uniffi::export(async_runtime = "tokio")]\n' +
      'impl SonaContext {\n' +
      `${methods.join('\n')}}\n`,
  };
}

export function currentSonaContextOperations() {
  const source = read(contextPath);
  const index = source.indexOf(OPERATIONS_MARKER);
  return index < 0 ? null : source.slice(index);
}

function main() {
  const { methods, block } = renderSonaContextOperations();
  const source = read(contextPath);
  const index = source.indexOf(OPERATIONS_MARKER);
  const head = index < 0 ? `${source.trimEnd()}\n` : source.slice(0, index);
  fs.writeFileSync(contextPath, head + block);
  console.log(`Generated ${methods} SonaContext operations in ${contextPath}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
